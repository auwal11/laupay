const DISPOSABLE_DOMAINS = new Set(
  [
    ...BUILT_IN_DISPOSABLE_DOMAINS,
    ...(process.env.DISPOSABLE_EMAIL_DOMAINS ?? '').split(','),
  ]
    .map((domain) => domain.trim().toLowerCase())
    .filter(Boolean),
);

export function normalizeEmail(email: string): string {
  return email.trim().toLowerCase();
}

export function emailDomain(email: string): string {
  const at = email.lastIndexOf('@');
  return at === -1 ? '' : email.slice(at + 1).trim().toLowerCase();
}

export function isDisposableEmail(email: string): boolean {
  const domain = emailDomain(normalizeEmail(email));
  if (!domain) return false;
  if (domain === 'example.com' || domain === 'example.net' || domain === 'example.org') return true;

  for (const blocked of DISPOSABLE_DOMAINS) {
    if (domain === blocked || domain.endsWith(`.${blocked}`)) return true;
  }
  return false;
}

export function assertEmailAllowed(email: string): string {
  const normalized = normalizeEmail(email);
  if (isDisposableEmail(normalized)) {
    throw new BadRequestException('Disposable email addresses are not allowed. Use a permanent email address.');
  }
  return normalized;
}
